import AppKit
import Synchronization

/// Every item on the pasteboard with every type's bytes, so a paste can be undone exactly,
/// including images, files, rich text and app-private types.
public struct PasteboardSnapshot: Sendable, Equatable {
    public struct Item: Sendable, Equatable {
        /// Type identifier → bytes, in the order the owner declared them.
        public var entries: [(type: String, data: Data)]

        public init(entries: [(type: String, data: Data)]) {
            self.entries = entries
        }

        public static func == (a: Item, b: Item) -> Bool {
            a.entries.map(\.type) == b.entries.map(\.type) && a.entries.map(\.data) == b.entries.map(\.data)
        }
    }

    public var items: [Item]

    public init(items: [Item]) {
        self.items = items
    }

    /// Marked secret by its owner (password managers), who will clear it on a timer.
    public var isConcealed: Bool {
        items.contains { $0.entries.contains { $0.type == PasteboardMarkers.concealed.rawValue } }
    }

    public static let empty = PasteboardSnapshot(items: [])
}

/// Our temporary write. `wasRead` turns true once some app has asked for the text.
public struct PasteWrite: Sendable {
    public let changeCount: Int
    public let wasRead: @Sendable () -> Bool

    public init(changeCount: Int, wasRead: @escaping @Sendable () -> Bool) {
        self.changeCount = changeCount
        self.wasRead = wasRead
    }
}

/// The pasteboard the inserter borrows. Real: `SystemPasteboard`. Fake: `FakePasteboard`.
@MainActor
public protocol PasteboardStore: AnyObject {
    var changeCount: Int { get }
    func snapshot() -> PasteboardSnapshot
    /// Replaces the contents with `text`, marked transient so clipboard managers skip it. The
    /// text is provided lazily, so the write reports when an app actually read it.
    func writeTransient(_ text: String) -> PasteWrite
    /// Puts `snapshot` back, marked auto-generated so clipboard history doesn't log it twice.
    func restore(_ snapshot: PasteboardSnapshot)
}

/// Markers from nspasteboard.org that clipboard history apps honour.
enum PasteboardMarkers {
    static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    static let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
}

/// Hands out the text only when an app asks for it, and remembers that it did.
final class LazyText: NSObject, NSPasteboardItemDataProvider, Sendable {
    let text: String
    private let read = Mutex(false)

    init(_ text: String) {
        self.text = text
    }

    var wasRead: Bool { read.withLock { $0 } }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        read.withLock { $0 = true }
        item.setString(text, forType: type)
    }
}

@MainActor
public final class SystemPasteboard: PasteboardStore {
    let pasteboard: NSPasteboard

    /// `.general` in the app; tests pass a uniquely named pasteboard.
    public init(_ pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    public var changeCount: Int { pasteboard.changeCount }

    public func snapshot() -> PasteboardSnapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item in
            PasteboardSnapshot.Item(entries: item.types.compactMap { type in
                item.data(forType: type).map { (type.rawValue, $0) }
            })
        }
        return PasteboardSnapshot(items: items)
    }

    public func writeTransient(_ text: String) -> PasteWrite {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        let provider = LazyText(text)
        item.setDataProvider(provider, forTypes: [.string])
        item.setData(Data(), forType: PasteboardMarkers.transient)
        item.setData(Data(), forType: PasteboardMarkers.autoGenerated)
        pasteboard.writeObjects([item])
        return PasteWrite(changeCount: pasteboard.changeCount, wasRead: { provider.wasRead })
    }

    public func restore(_ snapshot: PasteboardSnapshot) {
        pasteboard.clearContents()
        guard !snapshot.items.isEmpty else { return }
        let items = snapshot.items.map { saved in
            let item = NSPasteboardItem()
            for entry in saved.entries {
                item.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.type))
            }
            return item
        }
        items.first?.setData(Data(), forType: PasteboardMarkers.autoGenerated)
        pasteboard.writeObjects(items)
    }
}
